import { Conflict } from '@mcp-gateway/core';
import { msg, type ServerMessage } from '@mcp-gateway/i18n/server';
import type { CompositesRepo, DriftEvent, DriftEventsRepo, JsonObject, ProjectionsRepo, Source, Tool, ToolsRepo, ToolViewsRepo } from '@mcp-gateway/db';
import { infer } from '@mcp-ui-kit/view-spec';
import {
  diffTools,
  shortHash,
  summarizeDiff,
  type GenerateResult,
  type GeneratedTool,
  type ToolDiff,
} from '@mcp-gateway/openapi-toolgen';
import { suggestProjection } from '@mcp-gateway/projection';

export interface RegisterStats {
  created: number;
  updated: number;
  unchanged: number;
  removed: number;
  breaking: number;
  deprecated: number;
  restored: number;
  projectionsSuggested: number;
  /** Views inferred for new tools (ADR-022), stored as `suggested`. */
  viewsSuggested: number;
  compositesInvalidated: number;
  /** Warnings (e.g. a spec operation equivalent to a manual tool, which is not replaced). */
  warnings: string[];
}

export interface RegisterResult {
  stats: RegisterStats;
  driftEvents: DriftEvent[];
}

export interface RegisterDeps {
  tools: ToolsRepo;
  drift: DriftEventsRepo;
  /** Optional: stores a suggested projection for new list tools (F6.2). */
  projections?: ProjectionsRepo;
  /** Optional: invalidates composites that depend on tools with breaking drift/removed (F7b.5). */
  composites?: CompositesRepo;
  /** Optional: stores views inferred from the tool contract, inactive until approved (ADR-022). */
  views?: ToolViewsRepo;
}

const fields = (g: GeneratedTool) => ({
  name: g.name,
  title: g.title,
  description: g.description,
  operationRef: g.operationRef,
  inputSchema: g.inputSchema,
  outputSchema: g.outputSchema,
  annotations: g.annotations,
  specHash: g.specHash,
  tags: g.tags,
});

const diffPayload = (diff: ToolDiff, fromVersion: number | null, toVersion: number) => ({
  summary: summarizeDiff(diff),
  breaking: diff.breaking,
  changes: diff.changes,
  fromVersion,
  toVersion,
});

/**
 * Syncs the generated tools with the registry (PLAN F2.4):
 * - new → `disabled`, v1, drift `added`;
 * - changed and compatible → new version, keeps the state, drift `changed`;
 * - changed and breaking → new version, `disabled`, drift `breaking`;
 * - gone from the spec → `removed`, drift `removed`;
 * - became `deprecated` in the spec → `deprecated`.
 * Owner overrides live in their own column and are reapplied over the new version.
 * `manual`/`composite` tools are never touched.
 *
 * A NULL `spec_hash` on an `openapi` tool marks a row generated by an older toolgen format
 * (migration 0013, ADR-012: no persisted effect suffix, English schema texts). Its hash cannot be
 * compared, so when the diff finds no change the row is refreshed silently: same version, no drift.
 */
export async function registerTools(
  deps: RegisterDeps,
  tenantId: string,
  source: Pick<Source, 'id' | 'ownerTeam'>,
  generated: GenerateResult,
): Promise<RegisterResult> {
  const stats: RegisterStats = {
    created: 0,
    updated: 0,
    unchanged: 0,
    removed: 0,
    breaking: 0,
    deprecated: 0,
    restored: 0,
    projectionsSuggested: 0,
    viewsSuggested: 0,
    compositesInvalidated: 0,
    warnings: [],
  };
  const driftEvents: DriftEvent[] = [];
  const all = await deps.tools.listBySource(tenantId, source.id);
  const existing = all.filter((t) => t.kind === 'openapi');
  const manualByKey = new Map(
    all.filter((t) => t.kind === 'manual' && t.operationRef).map((t) => [`${t.operationRef!.method.toUpperCase()} ${t.operationRef!.path}`, t]),
  );
  const byKey = new Map(existing.map((t) => [t.operationKey ?? '', t]));
  const seen = new Set<string>();
  /** Tools that became unavailable (breaking/removed): input for the composite cascade. */
  const broken: Array<{ id: string; name: string; reason: ServerMessage }> = [];

  const drift = async (tool: Tool, kind: DriftEvent['kind'], diff: Record<string, unknown>) => {
    driftEvents.push(await deps.drift.create(tenantId, { toolId: tool.id, kind, diff }));
  };

  /** Retries the operation with a hashed variant of the name if it collides with another tenant tool. */
  const withUniqueName = async <T>(g: GeneratedTool, fn: (name: string) => Promise<T>): Promise<T> => {
    try {
      return await fn(g.name);
    } catch (err) {
      if (!(err instanceof Conflict)) throw err;
      return fn(`${g.name.slice(0, 57)}_${shortHash(`${source.id}:${g.operationKey}`)}`);
    }
  };

  for (const g of generated.tools) {
    seen.add(g.operationKey);
    const manual = manualByKey.get(g.operationKey);
    if (manual) {
      stats.warnings.push(`spec operation ${g.operationKey} matches manual tool ${manual.name} (kept; the generated one was also registered as ${g.name})`);
    }
    const current = byKey.get(g.operationKey);

    if (!current) {
      const tool = await withUniqueName(g, (name) =>
        deps.tools.create(tenantId, {
          kind: 'openapi',
          sourceId: source.id,
          operationKey: g.operationKey,
          ...fields(g),
          name,
          state: 'disabled',
          version: 1,
          ownerTeam: source.ownerTeam,
        }),
      );
      stats.created += 1;
      await drift(tool, 'added', { summary: 'new operation', fromVersion: null, toVersion: 1 });
      const suggestion = suggestProjection(g.outputSchema);
      if (suggestion && deps.projections && (await deps.projections.suggest(tenantId, tool.id, suggestion.include))) {
        stats.projectionsSuggested += 1;
      }
      const views = deps.views ? infer({ name: tool.name, ...(g.title ? { title: g.title } : {}), inputSchema: g.inputSchema, ...(g.outputSchema ? { outputSchema: g.outputSchema } : {}), annotations: g.annotations }) : undefined;
      if (views && (await deps.views!.suggest(tenantId, tool.id, views as unknown as JsonObject, views.version))) {
        stats.viewsSuggested += 1;
      }
      continue;
    }

    const wasRemoved = current.state === 'removed';
    if (current.specHash === g.specHash && !wasRemoved) {
      stats.unchanged += 1;
      continue;
    }

    const diff = diffTools(
      {
        name: current.name,
        description: current.description,
        inputSchema: current.inputSchema,
        outputSchema: current.outputSchema,
        annotations: current.annotations,
        operationRef: current.operationRef,
      },
      g,
    );
    if (current.specHash === null && !wasRemoved && !diff.changes.length) {
      await deps.tools.update(tenantId, current.id, { ...fields(g), name: current.name });
      stats.unchanged += 1;
      continue;
    }
    const hashChanged = current.specHash !== g.specHash;
    // The `deprecated` state (from the owner or the spec) only changes by owner action.
    const state = wasRemoved || diff.breaking ? 'disabled' : current.state;
    const version = hashChanged ? current.version + 1 : current.version;

    const tool = await withUniqueName(g, (name) =>
      deps.tools.update(
        tenantId,
        current.id,
        { ...fields(g), name, state, version },
        hashChanged ? { diff: diffPayload(diff, current.version, version) } : undefined,
      ),
    );

    if (wasRemoved) {
      stats.restored += 1;
      await drift(tool, 'added', { ...diffPayload(diff, current.version, version), summary: 'operation back in the spec' });
    } else if (diff.breaking) {
      stats.breaking += 1;
      stats.updated += 1;
      await drift(tool, 'breaking', diffPayload(diff, current.version, version));
      broken.push({ id: tool.id, name: tool.name, reason: msg('db.reasonBreakingChange', { summary: summarizeDiff(diff) }) });
    } else {
      stats.updated += 1;
      await drift(tool, 'changed', diffPayload(diff, current.version, version));
    }
  }

  const deprecatedKeys = new Set(generated.skipped.filter((s) => s.reason === 'deprecated').map((s) => s.operationKey));
  for (const t of existing) {
    if (seen.has(t.operationKey ?? '') || t.state === 'removed') continue;
    if (deprecatedKeys.has(t.operationKey ?? '')) {
      if (t.state !== 'deprecated') {
        const tool = await deps.tools.setState(tenantId, t.id, t.state, 'deprecated');
        stats.deprecated += 1;
        await drift(tool, 'changed', { summary: 'operation marked as deprecated in the spec', fromVersion: t.version, toVersion: t.version });
      }
      continue;
    }
    const tool = await deps.tools.setState(tenantId, t.id, t.state, 'removed');
    stats.removed += 1;
    await drift(tool, 'removed', { summary: 'operation removed from the spec', fromVersion: t.version, toVersion: t.version });
    broken.push({ id: tool.id, name: tool.name, reason: msg('db.reasonRemovedFromSpec') });
  }

  if (deps.composites && broken.length) {
    const cascade = await deps.composites.invalidateDependents(tenantId, broken);
    stats.compositesInvalidated = cascade.length;
    driftEvents.push(...cascade);
  }

  return { stats, driftEvents };
}
